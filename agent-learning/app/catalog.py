def _food_group(
    prefix: str,
    names: list[str],
    category: str,
    kcal_low: int,
    kcal_high: int,
    unit: str,
    grams: float,
    *,
    fdc_based: bool,
) -> list[FoodSeed]:
    seeds: list[FoodSeed] = []
    for index, name in enumerate(names, start=1):
        calibrated = name in KCAL_ESTIMATES
        kcal_value = KCAL_ESTIMATES.get(name, round((kcal_low + kcal_high) / 2))
        uncertainty_pct = FOOD_UNCERTAINTY.get(
            name,
            0.10 if fdc_based and calibrated else 0.22,
        )
        source_name = (
            "USDA FoodData Central 标准参考值 + 轻衡份量换算"
            if fdc_based and calibrated
            else "轻衡逐食物校准模型"
        )
        seeds.append(FoodSeed(
            id=f"{prefix}-{index:03d}",
            name=name,
            aliases=FOOD_ALIASES.get(name, ()),
            category=category,
            kcal_value=kcal_value,
            uncertainty_pct=uncertainty_pct,
            kcal_low=max(0, round(kcal_value * (1 - uncertainty_pct))),
            kcal_high=round(kcal_value * (1 + uncertainty_pct)),
            units={"克": 1.0, unit: grams} if unit != "克" else {"克": 1.0},
            source_name=source_name,
            source_version=FOOD_VERSION,
            source_url=FOOD_SOURCE_URL if fdc_based and calibrated else None,
        ))
    return seeds


